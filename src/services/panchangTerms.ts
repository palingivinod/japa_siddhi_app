const SORTED = entries.sort((a, b) => b.alias.length - a.alias.length);

const escapeRegExp = (value: string) => value.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');

export const translatePanchangValue = (
  text: string | undefined | null,
  language: string,
) => {
  const raw = String(text || '').trim();
  const lang = String(language || 'en')
    .trim()
    .toLowerCase()
    .slice(0, 2);
  if (!raw || lang === 'en') {
    return raw;
  }
  let out = raw;
  SORTED.forEach(entry => {
    const next = entry.words[lang as keyof Words];
    if (!next) {
      return;
    }
    const pattern = new RegExp(
      `(^|[^A-Za-z])(${escapeRegExp(entry.alias)})(?=$|[^A-Za-z])`,
      'gi',
    );
    out = out.replace(pattern, (_match, lead: string) => `${lead}${next}`);
  });
  return out;
};
