const titleFor = (milestone: number, lang: 'en' | 'te' | 'hi') => {
  if (lang === 'te') {
    return milestone >= 8000
      ? 'గమనిక: మీ 8,000 జపాల పూర్తి — ముఖ్య సూచన'
      : 'గమనిక: మీ 5,000 జపాల పూర్తి — ముఖ్య సూచన';
  }
  if (lang === 'hi') {
    return milestone >= 8000
      ? 'सूचना: आपके 8,000 जप पूरे — महत्वपूर्ण सुझाव'
      : 'सूचना: आपके 5,000 जप पूरे — महत्वपूर्ण सुझाव';
  }
  return milestone >= 8000
    ? 'Note: Your 8,000 Japas are complete — Important guidance'
    : 'Note: Your 5,000 Japas are complete — Important guidance';
};

const shortPush = (milestone: number) =>
  milestone >= 8000
    ? 'You completed 8,000 Japas. Open for Team Japa Siddhi guidance and eligible rewards.'
    : 'You completed 5,000 Japas. Open for Team Japa Siddhi guidance and eligible rewards.';

const buildTranslations = (milestone: number) => {
  const pack: Record<string, {title: string; message: string}> = {
    en: {title: titleFor(milestone, 'en'), message: BODY_EN},
    te: {title: titleFor(milestone, 'te'), message: BODY_TE},
    hi: {title: titleFor(milestone, 'hi'), message: BODY_HI},
  };
  // Other app languages fall back to English in the pack.
  for (const code of ['ta', 'kn', 'ml', 'mr', 'bn', 'or']) {
    pack[code] = {title: titleFor(milestone, 'en'), message: BODY_EN};
  }
  return pack;
};

/**
 * Create inbox notification at absolute 5k / 8k if devotee has not ordered
 * Baanalingam or Markata yet. Idempotent per milestone.
 */
export const ensureLingamAdviceNotifications = async (
  userId: number,
  previousTotal: number,
  currentTotal: number,
) => {
  if (!userId || currentTotal < 5000) {
    return;
  }
  try {
    if (await shivaLingaEligibilityService.hasActiveBaanalingam(userId)) {
      return;
    }
    if (await shivaLingaEligibilityService.hasActiveMarakata(userId)) {
      return;
    }
  } catch {
    // Continue — better to notify than silently skip on eligibility error.
  }

  const milestones = [5000, 8000].filter(
    m => previousTotal < m && currentTotal >= m,
  );

  for (const milestone of milestones) {
    const exists = await notificationService.existsByAction(
      userId,
      LINGAM_ADVICE_ACTION,
      milestone,
    );
    if (exists) {
      continue;
    }
    const translations = buildTranslations(milestone);
    await notificationService.create({
      userId,
      title: translations.en.title,
      message: shortPush(milestone),
      notificationType: 'REWARD',
      actionType: LINGAM_ADVICE_ACTION,
      actionId: milestone,
      extraData: {
        kind: 'lingam_advice',
        milestone,
        showGrabReward: true,
        pushTitle: translations.en.title,
        pushBody: shortPush(milestone),
        translations,
      },
    });
  }
};
